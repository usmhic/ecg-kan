"""Generate manuscript tables from saved results, without running experiments.

Run with --check to reject stale tables. Uses only the Python standard library.
"""
import argparse
import csv
import re
from pathlib import Path
import statistics

ROOT = Path(__file__).resolve().parents[1]
RUNS = ("1_same_recording_gaussian", "2_new_recording_gaussian",
        "3_new_recording_morlet")
MODELS = ("OC-SVM", "Isolation Forest", "LOF", "Elliptic Envelope",
          "MLP Autoencoder", "KAN Autoencoder")
METRICS = ("AUROC", "F1", "EER")


def read_rows(run, filename):
    with (ROOT / "results" / run / "metrics" / filename).open(
            encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def label(model):
    return model.replace("Autoencoder", "autoencoder")


def benchmark(run):
    return {(('raw' if r['Feature set'].startswith('Raw') else 'wtmm'),
             r['Model'], r['Metric']): r
            for r in read_rows(run, "benchmark_results.csv")}


def cell(row, sd=False, best=False):
    mean = f"{float(row['Mean']):.3f}"
    if best:
        mean = r"\textbf{" + mean + "}"
    spread = (f"$\\pm${float(row['Std']):.3f}" if sd else "")
    # Keep uncertainty on its own line so the paper needs no font shrinking.
    return (r"\shortstack[l]{" + f"{mean}{spread}" + r"\\[.2ex]{}"
            + f"[{float(row['CI95 low']):.3f}, "
            f"{float(row['CI95 high']):.3f}]" + "}")


def best_mean(rows, feature, model, metric):
    values = [round(float(rows[feature, m, metric]['Mean']), 3) for m in MODELS]
    best = min(values) if metric == "EER" else max(values)
    return round(float(rows[feature, model, metric]['Mean']), 3) == best


def tabular(columns, headings, rows):
    wide = len(columns) == 4
    opening = (r"\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}"
               + columns + r"@{}}" if wide else r"\begin{tabular}{" + columns + "}")
    closing = r"\end{tabular*}" if wide else r"\end{tabular}"
    if wide:
        rows = [row + "[3pt]" if row.endswith(r"\\") else row for row in rows]
    return (r"% Generated by research/build_paper_tables.py; do not edit." + "\n"
            + opening + r"\toprule" + "\n"
            + " & ".join(headings) + r" \\\midrule" + "\n"
            + "\n".join(rows) + "\n" + r"\bottomrule" + closing + "\n")


def generated_tables():
    primary = benchmark(RUNS[0])
    rows = []
    for feature, title in (("raw", "Waveform with enrolment-fitted PCA"),
                           ("wtmm", "WTMM-inspired summary (26 features)")):
        if rows:
            rows.append(r"\midrule")
        rows.append(r"\multicolumn{4}{l}{\textit{" + title + r"}} \\")
        for model in MODELS:
            rows.append(" & ".join([label(model)] + [cell(
                primary[feature, model, metric], sd=True,
                best=best_mean(primary, feature, model, metric))
                for metric in METRICS]) + r" \\")
    tables = {"primary.tex": tabular("llll", ["Model", "AUROC", "$F_1$", "EER"], rows)}

    paired = {(r['comparator'], r['metric']): r for r in
              read_rows(RUNS[0], "paired_comparisons.csv") if r['feature_set'] == 'wtmm'}
    rows = []
    for model in (MODELS[-2], *MODELS[:4]):
        cells = []
        for metric in ("auroc", "f1", "eer"):
            r = paired[model, metric]
            # Four decimals avoid negative zero and show very small differences.
            cells.append(r"\shortstack[l]{"
                         + f"${float(r['mean_KAN_advantage']):+.4f}$" + r"\\[.2ex]{}"
                         + f"[${float(r['CI95_low']):.4f}$, ${float(r['CI95_high']):.4f}$]" + "}")
        rows.append(" & ".join([label(model), *cells]) + r" \\")
    tables['paired.tex'] = tabular("llll", ["Baseline", "AUROC", "$F_1$", "EER"], rows)

    rows = []
    for run, wavelet in zip(RUNS[1:], ("Gaussian derivative", "Morlet")):
        values = benchmark(run)
        if rows:
            rows.append(r"\midrule")
        rows.append(r"\multicolumn{4}{l}{\textit{" + wavelet + r"}} \\")
        for model in MODELS:
            rows.append(" & ".join([label(model)] + [cell(
                values['wtmm', model, metric],
                best=best_mean(values, 'wtmm', model, metric))
                for metric in METRICS]) + r" \\")
    tables['second_recording.tex'] = tabular(
        "llll", ["Model", "AUROC", "$F_1$", "EER"], rows)

    people = read_rows(RUNS[0], "per_subject_long.csv")
    rows = []
    for cohort, start, stop in (("01--10", 1, 10), ("11--30", 11, 30)):
        for model in (MODELS[0], *MODELS[-2:]):
            means = [statistics.mean(float(r['value']) for r in people
                     if r['feature_set'] == 'wtmm' and r['model'] == model
                     and r['metric'] == metric.lower()
                     and start <= int(r['subject']) <= stop) for metric in METRICS]
            rows.append(" & ".join([cohort, label(model), *(f"{x:.3f}" for x in means)]) + r" \\")
    tables['cohorts.tex'] = tabular(
        "lllll", ["Persons", "Model", "AUROC", "$F_1$", "EER"], rows)
    return tables


def embed_tables(manuscript, tables):
    """Keep the uploadable manuscript independent of external table files."""
    for name, content in tables.items():
        start, end = f"% BEGIN GENERATED TABLE: {name}", f"% END GENERATED TABLE: {name}"
        block = start + "\n" + content + end
        pattern = re.escape(start) + r".*?" + re.escape(end)
        if re.search(pattern, manuscript, flags=re.DOTALL):
            manuscript = re.sub(pattern, lambda _: block, manuscript, flags=re.DOTALL)
        else:
            original = r"\input{tables/" + name + "}"
            if original not in manuscript:
                raise ValueError(f"Missing manuscript table location: {name}")
            manuscript = manuscript.replace(original, block)
    return manuscript


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "paper" / "tables"
    if not args.check:
        destination.mkdir(exist_ok=True)
    tables = generated_tables()
    for name, content in tables.items():
        path = destination / name
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise SystemExit(f"Stale or missing table: {path}")
        else:
            path.write_text(content, encoding='utf-8')
    manuscript_path = ROOT / "paper/main.tex"
    manuscript = manuscript_path.read_text(encoding='utf-8')
    updated = embed_tables(manuscript, tables)
    if args.check:
        if manuscript != updated:
            raise SystemExit("Stale embedded manuscript tables; run research/build_paper_tables.py")
    else:
        manuscript_path.write_text(updated, encoding='utf-8')
    print("Manuscript tables match saved results." if args.check
          else "Wrote four table files and embedded them in paper/main.tex.")


if __name__ == "__main__":
    main()
